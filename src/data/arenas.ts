import { ArenaDefinition, DestructibleSpec } from '../types/game';

function createRingDestructibles(
  prefix: string,
  outerType: DestructibleSpec['type'],
  outerName: string,
  outerPayout: DestructibleSpec['payoutType'],
  outerColor: string,
  innerType: DestructibleSpec['type'],
  innerName: string,
  innerPayout: DestructibleSpec['payoutType'],
  innerColor: string
): DestructibleSpec[] {
  const items: DestructibleSpec[] = [];
  // 6 outer ring pillars at radius 24m
  for (let i = 0; i < 6; i++) {
    const angle = (i / 6) * Math.PI * 2;
    const x = Number((Math.cos(angle) * 24).toFixed(2));
    const z = Number((Math.sin(angle) * 24).toFixed(2));
    items.push({
      id: `${prefix}_outer_${i + 1}`,
      name: `${outerName} #${i + 1}`,
      type: outerType,
      position: [x, 0, z],
      maxHp: 420,
      radius: 2.1,
      payoutType: outerPayout,
      color: outerColor,
    });
  }
  // 4 inner tactical crystal/condenser nodes at radius 12m
  for (let i = 0; i < 4; i++) {
    const angle = (i / 4) * Math.PI * 2 + Math.PI / 4;
    const x = Number((Math.cos(angle) * 12).toFixed(2));
    const z = Number((Math.sin(angle) * 12).toFixed(2));
    items.push({
      id: `${prefix}_inner_${i + 1}`,
      name: `${innerName} #${i + 1}`,
      type: innerType,
      position: [x, 0, z],
      maxHp: 280,
      radius: 1.6,
      payoutType: innerPayout,
      color: innerColor,
    });
  }
  return items;
}

